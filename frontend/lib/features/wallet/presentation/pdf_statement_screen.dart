class PdfStatementScreen extends StatefulWidget {
  final String activeToken;

  PdfStatementScreen({
    super.key,
    required this.activeToken,
  });

  @override
  State<PdfStatementScreen> createState() => _PdfStatementScreenState();
}

class _PdfStatementScreenState extends State<PdfStatementScreen> {
  // ==========================================================
  // STATE
  // ==========================================================

  String _selectedCurrency = 'USD';

  DateTime? _startDate;
  DateTime? _endDate;

  bool _isGenerating = false;
  String? _lastSavedFilePath;

  // ==========================================================
  // COLORS
  // ==========================================================

  static Color get _backgroundColor => AppColors.adaptiveSurfaceAlt;
  static Color get _cardColor => AppColors.adaptiveSurface;
  static const Color _secondaryText = Color(0xFFD7E0E3);
  static const Color _mutedText = Color(0xFFB7C4C8);

  // ==========================================================
  // DATE FORMAT
  // ==========================================================

  String _formatDate(DateTime? date) {
    if (date == null) {
      return '';
    }

    final year = date.year.toString().padLeft(4, '0');
    final month = date.month.toString().padLeft(2, '0');
    final day = date.day.toString().padLeft(2, '0');

    return '$year-$month-$day';
  }

  String _displayDate(DateTime? date) {
    if (date == null) {
      return 'Select date';
    }

    const months = [
      'Jan',
      'Feb',
      'Mar',
      'Apr',
      'May',
      'Jun',
      'Jul',
      'Aug',
      'Sep',
      'Oct',
      'Nov',
      'Dec',
    ];

    return '${months[date.month - 1]} ${date.day}, ${date.year}';
  }

  // ==========================================================
  // DATE PICKER
  // ==========================================================

  Future<void> _selectStartDate() async {
    final now = DateTime.now();

    final picked = await showDatePicker(
      context: context,
      initialDate: _startDate ?? DateTime(now.year, now.month, 1),
      firstDate: DateTime(2020),
      lastDate: now,
      builder: (context, child) {
        return Theme(
          data: Theme.of(context).copyWith(
            colorScheme: ColorScheme.dark(
              primary: AppColors.neonPink,
              surface: _cardColor,
            ),
          ),
          child: child!,
        );
      },
    );

    if (picked == null) {
      return;
    }

    setState(() {
      _startDate = picked;

      if (_endDate != null && _endDate!.isBefore(picked)) {
        _endDate = picked;
      }
    });
  }

  Future<void> _selectEndDate() async {
    final now = DateTime.now();

    final firstDate = _startDate ?? DateTime(2020);

    final picked = await showDatePicker(
      context: context,
      initialDate: _endDate ?? now,
      firstDate: firstDate,
      lastDate: now,
      builder: (context, child) {
        return Theme(
          data: Theme.of(context).copyWith(
            colorScheme: ColorScheme.dark(
              primary: AppColors.neonPink,
              surface: _cardColor,
            ),
          ),
          child: child!,
        );
      },
    );

    if (picked == null) {
      return;
    }

    setState(() {
      _endDate = picked;
    });
  }

  // ==========================================================
  // QUICK RANGE — CURRENT MONTH
  // ==========================================================

  void _setCurrentMonth() {
    final now = DateTime.now();

    setState(() {
      _startDate = DateTime(now.year, now.month, 1);
      _endDate = DateTime(now.year, now.month, now.day);
    });
  }

  // ==========================================================
  // QUICK RANGE — LAST 30 DAYS
  // ==========================================================

  void _setLast30Days() {
    final now = DateTime.now();

    setState(() {
      _startDate = DateTime(
        now.year,
        now.month,
        now.day,
      ).subtract(
        Duration(days: 29),
      );

      _endDate = DateTime(
        now.year,
        now.month,
        now.day,
      );
    });
  }

  // ==========================================================
  // CLEAR DATE FILTER
  // ==========================================================

  void _clearDates() {
    setState(() {
      _startDate = null;
      _endDate = null;
    });
  }

  // ==========================================================
  // CURRENCY SYMBOL
  // ==========================================================

  String get _currencySymbol {
    return _selectedCurrency == 'KHR' ? '៛' : '\$';
  }

  // ==========================================================
  // GENERATE PDF
  // ==========================================================

  Future<void> _generateStatement() async {
    if (_isGenerating) {
      return;
    }

    // Safety check.
    if (widget.activeToken.trim().isEmpty) {
      _showError(
        'Your session is missing. Please login again.',
      );
      return;
    }

    // Safety check for invalid date range.
    if (_startDate != null &&
        _endDate != null &&
        _endDate!.isBefore(_startDate!)) {
      _showError(
        'End date cannot be earlier than start date.',
      );
      return;
    }

    setState(() {
      _isGenerating = true;
    });

    try {
      debugPrint('========================================');
      debugPrint('📄 US-075-A GENERATING PDF STATEMENT');
      debugPrint('💱 Currency: $_selectedCurrency');
      debugPrint('📅 Start: ${_formatDate(_startDate)}');
      debugPrint('📅 End: ${_formatDate(_endDate)}');
      debugPrint('========================================');

      final Uint8List pdfBytes =
      await WalletService.downloadPdfStatement(
        token: widget.activeToken,
        currency: _selectedCurrency,
        startDate:
        _startDate == null ? null : _formatDate(_startDate),
        endDate:
        _endDate == null ? null : _formatDate(_endDate),
      );

      if (pdfBytes.isEmpty) {
        throw Exception(
          'The server returned an empty PDF.',
        );
      }

      debugPrint(
        '✅ PDF received: ${pdfBytes.length} bytes',
      );

      final savedPath = await _savePdfFile(pdfBytes);

      if (!mounted) {
        return;
      }

      setState(() {
        _lastSavedFilePath = savedPath;
      });

      // ======================================================
      // WEB
      // ======================================================

      if (kIsWeb) {
        await _sharePdfOnWeb(pdfBytes);

        if (!mounted) {
          return;
        }

        _showSuccess(
          'PDF statement is ready to share.',
        );

        return;
      }

      // ======================================================
      // MOBILE / DESKTOP
      // ======================================================

      await _openPdfFile(savedPath);

      if (!mounted) {
        return;
      }

      _showSuccess(
        'PDF statement generated successfully.',
      );
    } catch (e) {
      debugPrint(
        '❌ PDF statement error: $e',
      );

      if (!mounted) {
        return;
      }

      String message = e.toString();

      if (message.startsWith('Exception:')) {
        message = message.substring(
          'Exception:'.length,
        ).trim();
      }

      _showError(message);
    } finally {
      if (mounted) {
        setState(() {
          _isGenerating = false;
        });
      }
    }
  }

  // ==========================================================
  // SAVE PDF FILE
  // ==========================================================

  Future<String> _savePdfFile(
      Uint8List pdfBytes,
      ) async {
    if (kIsWeb) {
      return '';
    }

    final directory =
    await getApplicationDocumentsDirectory();

    final statementsDirectory = Directory(
      '${directory.path}/NaNa Wallet/Statements',
    );

    if (!await statementsDirectory.exists()) {
      await statementsDirectory.create(
        recursive: true,
      );
    }

    final start =
    _formatDate(_startDate).replaceAll('-', '');

    final end =
    _formatDate(_endDate).replaceAll('-', '');

    final startPart =
    start.isEmpty ? 'DEFAULT' : start;

    final endPart =
    end.isEmpty ? 'DEFAULT' : end;

    final fileName =
        'NaNa-Wallet-Statement-'
        '${_selectedCurrency.toUpperCase()}-'
        '$startPart-'
        '$endPart.pdf';

    final file = File(
      '${statementsDirectory.path}/$fileName',
    );

    await file.writeAsBytes(
      pdfBytes,
      flush: true,
    );

    debugPrint(
      '💾 PDF saved to: ${file.path}',
    );

    return file.path;
  }

  // ==========================================================
  // OPEN PDF
  // ==========================================================

  Future<void> _openPdfFile(
      String filePath,
      ) async {
    if (filePath.isEmpty) {
      throw Exception(
        'PDF file path is empty.',
      );
    }

    debugPrint(
      '📖 Opening PDF: $filePath',
    );

    final result = await OpenFilex.open(
      filePath,
      type: 'application/pdf',
    );

    debugPrint(
      '📖 Open PDF result: '
          '${result.type} - ${result.message}',
    );

    if (result.type != ResultType.done) {
      throw Exception(
        'PDF was saved successfully, but could not be opened. '
            'You can open it manually from the saved location.',
      );
    }
  }

  // ==========================================================
  // SHARE PDF — WEB
  // ==========================================================

  Future<void> _sharePdfOnWeb(
      Uint8List pdfBytes,
      ) async {
    final fileName =
        'NaNa-Wallet-Statement-'
        '${_selectedCurrency.toUpperCase()}.pdf';

    await SharePlus.instance.share(
      ShareParams(
        files: [
          XFile.fromData(
            pdfBytes,
            name: fileName,
            mimeType: 'application/pdf',
          ),
        ],
        subject: 'NaNa Wallet PDF Statement',
        text: 'NaNa Wallet transaction statement.',
      ),
    );
  }

  // ==========================================================
  // SHARE SAVED PDF
  // ==========================================================

  Future<void> _shareSavedPdf() async {
    if (kIsWeb) {
      return;
    }

    final path = _lastSavedFilePath;

    if (path == null || path.isEmpty) {
      _showError(
        'Please generate a PDF statement first.',
      );
      return;
    }

    final file = File(path);

    if (!await file.exists()) {
      _showError(
        'The saved PDF could not be found. '
            'Please generate the statement again.',
      );
      return;
    }

    try {
      await SharePlus.instance.share(
        ShareParams(
          files: [
            XFile(
              path,
              mimeType: 'application/pdf',
            ),
          ],
          subject: 'NaNa Wallet PDF Statement',
          text: 'NaNa Wallet transaction statement.',
        ),
      );
    } catch (e) {
      debugPrint(
        '❌ Share PDF error: $e',
      );

      if (!mounted) {
        return;
      }

      _showError(
        'Unable to share the PDF.',
      );
    }
  }

  // ==========================================================
  // SHOW SAVED LOCATION
  // ==========================================================

  void _showSavedLocation() {
    final path = _lastSavedFilePath;

    if (path == null || path.isEmpty) {
