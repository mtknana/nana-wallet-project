  Widget _buildAfterDownloadActions() {
    return Row(
      children: [
        Expanded(
          child: OutlinedButton.icon(
            onPressed: _isGenerating
                ? null
                : () async {
              final path =
                  _lastSavedFilePath;

              if (path == null ||
                  path.isEmpty) {
                return;
              }

              try {
                await _openPdfFile(path);
              } catch (e) {
                if (!mounted) {
                  return;
                }

                _showError(
                  e.toString()
                      .replaceFirst(
                    'Exception:',
                    '',
                  )
                      .trim(),
                );
              }
            },
            icon: Icon(
              LucideIcons.fileText,
              size: 18,
            ),
            label: Text(
              'OPEN PDF',
