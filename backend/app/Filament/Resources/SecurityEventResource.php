<?php

namespace App\Filament\Resources;

use App\Filament\Resources\SecurityEventResource\Pages;
use App\Models\SecurityEvent;
use Filament\Forms\Form;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Table;
use Illuminate\Database\Eloquent\Builder;

class SecurityEventResource extends Resource
{
    protected static ?string $model = SecurityEvent::class;

    protected static ?string $navigationIcon = 'heroicon-o-shield-exclamation';

    protected static ?string $navigationLabel = 'Security Events';

    protected static ?string $navigationGroup = 'Security & Monitoring';

    protected static ?int $navigationSort = 1;

    protected static ?string $modelLabel = 'Security Event';

    protected static ?string $pluralModelLabel = 'Security Events';

    /**
     * Security events are generated by the system.
     * Admins should not manually create/edit them.
     */
    public static function form(Form $form): Form
    {
        return $form
            ->schema([
                //
            ]);
    }

    public static function table(Table $table): Table
    {
        return $table
            ->defaultSort('occurred_at', 'desc')

            ->columns([

                // =====================================================
                // EVENT
                // =====================================================

                Tables\Columns\TextColumn::make('event_type')
                    ->label('Event Type')
                    ->badge()
                    ->searchable()
                    ->sortable()
                    ->color(fn(string $state): string => match ($state) {
                        'login_success' => 'success',
                        'login_failed' => 'danger',
                        'logout' => 'gray',

                        'pin_created',
                        'pin_changed',
                        'pin_verified' => 'success',

                        'pin_failed' => 'danger',

                        '2fa_enabled',
                        '2fa_disabled' => 'warning',

                        'suspicious_activity',
                        'fraud_detected' => 'danger',

                        'security_alert' => 'warning',

                        default => 'info',
                    }),

                Tables\Columns\TextColumn::make('title')
                    ->label('Title')
                    ->searchable()
                    ->sortable()
                    ->limit(45),

                // =====================================================
                // USER
                // =====================================================

                Tables\Columns\TextColumn::make('user.name')
                    ->label('User')
                    ->searchable()
                    ->sortable()
                    ->placeholder('System'),

                Tables\Columns\TextColumn::make('user.email')
                    ->label('Email')
                    ->searchable()
                    ->toggleable(),

                // =====================================================
                // SEVERITY
                // =====================================================

                Tables\Columns\TextColumn::make('severity')
                    ->label('Severity')
                    ->badge()
                    ->searchable()
                    ->sortable()
                    ->color(fn(string $state): string => match ($state) {
                        'info' => 'info',
                        'warning' => 'warning',
                        'danger' => 'danger',
                        'critical' => 'danger',
                        default => 'gray',
                    }),

                // =====================================================
                // REVIEW STATUS
                // =====================================================

                Tables\Columns\IconColumn::make('is_reviewed')
                    ->label('Reviewed')
                    ->boolean()
                    ->sortable(),

                // =====================================================
                // DATE / TIME
                // =====================================================

                Tables\Columns\TextColumn::make('occurred_at')
                    ->label('Occurred At')
                    ->dateTime('d M Y, H:i:s')
                    ->sortable(),

                // =====================================================
                // IP ADDRESS
                // =====================================================

                Tables\Columns\TextColumn::make('ip_address')
                    ->label('IP Address')
                    ->toggleable(isToggledHiddenByDefault: true)
                    ->searchable(),

            ])

            // =========================================================
            // FILTERS
            // =========================================================

            ->filters([

                Tables\Filters\SelectFilter::make('event_type')
                    ->label('Event Type')
                    ->options([
                        'login_success' => 'Login Success',
                        'login_failed' => 'Login Failed',
                        'logout' => 'Logout',

                        'pin_created' => 'PIN Created',
                        'pin_changed' => 'PIN Changed',
                        'pin_verified' => 'PIN Verified',
                        'pin_failed' => 'PIN Failed',

                        '2fa_enabled' => '2FA Enabled',
                        '2fa_disabled' => '2FA Disabled',

                        'suspicious_activity' => 'Suspicious Activity',
                        'fraud_detected' => 'Fraud Detected',
                        'security_alert' => 'Security Alert',
                    ]),

                Tables\Filters\SelectFilter::make('severity')
                    ->options([
                        'info' => 'Info',
                        'warning' => 'Warning',
                        'danger' => 'Danger',
                        'critical' => 'Critical',
                    ]),

                Tables\Filters\TernaryFilter::make('is_reviewed')
                    ->label('Review Status')
                    ->placeholder('All Events')
                    ->trueLabel('Reviewed')
                    ->falseLabel('Not Reviewed'),

                Tables\Filters\SelectFilter::make('user_id')
                    ->label('User')
                    ->relationship('user', 'name')
                    ->searchable()
                    ->preload(),
            ])

            // =========================================================
            // ACTIONS
            // =========================================================

            ->actions([

                // View full security event
                Tables\Actions\ViewAction::make(),

                // Mark event as reviewed
                Tables\Actions\Action::make('mark_reviewed')
                    ->label('Mark Reviewed')
                    ->icon('heroicon-o-check-circle')
                    ->color('success')
                    ->visible(fn(SecurityEvent $record): bool => !$record->is_reviewed)
                    ->requiresConfirmation()
                    ->action(function (SecurityEvent $record): void {
                        $record->update([
                            'is_reviewed' => true,
                        ]);
                    }),
            ])

            // =========================================================
            // BULK ACTIONS
            // =========================================================

            ->bulkActions([
                Tables\Actions\BulkActionGroup::make([
                    Tables\Actions\BulkAction::make('mark_reviewed')
                        ->label('Mark as Reviewed')
                        ->icon('heroicon-o-check-circle')
                        ->color('success')
                        ->requiresConfirmation()
                        ->action(function ($records): void {
                            $records->each(function (SecurityEvent $record) {
                                $record->update([
                                    'is_reviewed' => true,
                                ]);
                            });
                        }),

                    Tables\Actions\DeleteBulkAction::make(),
                ]),
            ]);
    }

    // ================================================================
    // RELATIONS
    // ================================================================

    public static function getRelations(): array
    {
        return [
            //
        ];
    }

    // ================================================================
    // PAGES
    // ================================================================

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListSecurityEvents::route('/'),

            // We don't want admins manually creating security events.
            // 'create' => Pages\CreateSecurityEvent::route('/create'),

            // We don't want admins manually editing security events.
            // 'edit' => Pages\EditSecurityEvent::route('/{record}/edit'),
        ];
    }
}